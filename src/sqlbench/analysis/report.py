"""reports/<version>/README.md and its charts, generated from one exported run.

Every number in the report is computed here or in tables.py from stored
files: the run's Parquet and manifest, the question files, the guard
checks and labels.csv. The prose only names what a table shows.
"""

import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from sqlbench.analysis import charts
from sqlbench.analysis.guard_check import GuardCheck
from sqlbench.analysis.hand_labels import HandLabel, RootCause, agreement, order_key
from sqlbench.analysis.stats import LEVEL, RESAMPLES, SEED, Interval
from sqlbench.analysis.tables import (
    FAILURE_LABELS,
    WAREHOUSES,
    RunData,
    accuracy_by_group,
    accuracy_by_warehouse,
    failure_labels,
    failure_outcomes,
    failures_by_divergence,
    group_gaps,
    lucky_rates,
    neighbour_gaps,
    pick_examples,
    split_questions,
)
from sqlbench.harness.store import ResultRow
from sqlbench.questions.model import Category, Difficulty, Divergence, Feature
from sqlbench.warehouses.base import WarehouseName

NOT_SIGNIFICANT = "n.s."
REQUEST_ID = re.compile(r"\s*\(request_id=[^)]*\)")
ERROR_CHARS = 200


@dataclass(frozen=True)
class ReportInputs:
    data: RunData
    manifest: dict[str, object]
    guard_checks: list[GuardCheck] | None
    hand_labels: list[HandLabel]
    # Who made labels.csv, as the report should state it ("by hand", "by an LLM agent").
    labeller: str


def percent(value: float) -> str:
    return f"{value * 100:.1f}%"


def with_interval(interval: Interval) -> str:
    return f"{percent(interval.estimate)} [{interval.low * 100:.1f}, {interval.high * 100:.1f}]"


def gap_text(interval: Interval) -> str:
    text = (
        f"{interval.estimate * 100:+.1f} pp [{interval.low * 100:+.1f}, {interval.high * 100:+.1f}]"
    )
    if not interval.excludes_zero:
        text += f" {NOT_SIGNIFICANT}"
    return text


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return lines


def short_error(text: str | None) -> str:
    """The error on one line. Snowflake puts the detail on the line after the code."""
    if not text:
        return ""
    # Databricks repeats the whole query after "== SQL =="; the SQL is shown elsewhere.
    without_echo = text.split("== SQL ==")[0]
    without_ids = REQUEST_ID.sub("", without_echo)
    return " ".join(without_ids.split())[:ERROR_CHARS]


def code_span(text: str) -> str:
    """Inline code that may itself contain backticks (Databricks quotes names with them)."""
    return f"`` {text} ``"


def header_section(inputs: ReportInputs) -> list[str]:
    manifest = inputs.manifest
    data = inputs.data
    return [
        f"# Warehouse SQL Bench {manifest['run_id']}: results",
        "",
        "Generated by `bench report` from `results/run-"
        f"{manifest['run_id']}.parquet`. Every number below comes from code.",
        "",
        *table(
            ["", ""],
            [
                ["questions", str(len(data.question_ids))],
                ["models", str(len(data.models))],
                ["warehouses", ", ".join(WAREHOUSES)],
                ["scored tasks", str(len(data.rows))],
                ["run", f"{manifest['started_at_utc']} to {manifest['finished_at_utc']} UTC"],
                ["git sha", str(manifest["git_sha"])],
                ["question set sha256", str(manifest["question_set_sha256"])],
                ["data sha256", str(manifest["data_manifest_sha256"])],
                ["scorer version", str(manifest["scorer_version"])],
                ["results file sha256", str(manifest["parquet_sha256"])],
            ],
        ),
        "A task is correct only if its result matches gold on both the main and the edge dataset.",
        "",
    ]


def failure_section(inputs: ReportInputs) -> list[str]:
    data = inputs.data
    outcomes = failure_outcomes(data)
    labels = failure_labels(data)
    names = sorted({outcome for counts in outcomes.values() for outcome in counts})
    lines = [
        "## 1. Why predictions fail",
        "",
        "![Failures by warehouse](failures.png)",
        "",
        "### By outcome",
        "",
    ]
    rows = [[name] + [str(outcomes[w][name]) for w in WAREHOUSES] for name in names]
    rows.append(["**all failures**"] + [str(sum(outcomes[w].values())) for w in WAREHOUSES])
    lines += table(["outcome", *WAREHOUSES], rows)
    lines += [
        "### By automatic label",
        "",
        "A failure can carry several labels or none. Definitions are in "
        "`src/sqlbench/analysis/labels.py`.",
        "",
    ]
    label_rows = [
        [str(label)] + [str(labels[w][label]) for w in WAREHOUSES] for label in FAILURE_LABELS
    ]
    lines += table(["label", *WAREHOUSES], label_rows)
    lines += ["### By divergence type", ""]
    divergence_rows = []
    for entry in failures_by_divergence(data):
        common = ", ".join(f"{name} {count}" for name, count in entry.outcomes.most_common(3))
        divergence_rows.append(
            [
                entry.divergence,
                entry.warehouse,
                str(entry.tasks),
                str(entry.failures),
                percent(entry.failures / entry.tasks) if entry.tasks else "",
                common,
            ]
        )
    lines += table(
        ["divergence", "warehouse", "tasks", "failed", "failure rate", "most common outcomes"],
        divergence_rows,
    )
    return lines


def example_section(inputs: ReportInputs) -> list[str]:
    data = inputs.data
    lines = [
        "## 2. Example failures",
        "",
        "One failure per category, picked by a hash of the task, preferring a model not "
        "shown yet. Predicted result rows aren't stored, so each example shows the outcome "
        "on each dataset and the warehouse's error.",
        "",
    ]
    for title, row in pick_examples(data, order_key):
        question = data.questions[row.question_id]
        gold = question.gold_sql.for_warehouse(WarehouseName(row.warehouse)).strip()
        labels = ", ".join(data.labels_of(row)) or "none"
        lines += [
            f"### {title}: {row.question_id}, {row.model_id} on {row.warehouse}",
            "",
            f"> {question.question}",
            "",
            f"main: {row.outcome_main}; edge: {row.outcome_edge}; labels: {labels}",
            "",
        ]
        if row.error_message:
            lines += [f"Error: {code_span(short_error(row.error_message))}", ""]
        lines += [
            "Predicted:",
            "",
            "```sql",
            (row.predicted_sql or "(no SQL)").strip(),
            "```",
            "",
            "Gold:",
            "",
            "```sql",
            gold,
            "```",
            "",
        ]
    return lines


def why(row: ResultRow, labels: tuple[str, ...]) -> str:
    parts = [row.outcome]
    parts += [label for label in labels if label in FAILURE_LABELS]
    parts += list(row.near_miss)
    error = short_error(row.error_message)
    text = ", ".join(parts)
    if error:
        text += f": {code_span(error[:90])}"
    return text


def split_section(inputs: ReportInputs) -> list[str]:
    data = inputs.data
    splits = split_questions(data)
    lines = [
        "## 3. Same question, different warehouse",
        "",
        "Questions a model answered correctly on one warehouse and not on the other.",
        "",
    ]
    summary = []
    for model_id in data.models:
        entries = splits[model_id]
        snowflake_only = sum(1 for entry in entries if entry.right_on == WAREHOUSES[0])
        summary.append([model_id, str(snowflake_only), str(len(entries) - snowflake_only)])
    lines += table(["model", "right on snowflake only", "right on databricks only"], summary)
    detail = []
    for model_id in data.models:
        for entry in splits[model_id]:
            detail.append(
                [
                    model_id,
                    entry.question_id,
                    entry.right_on,
                    why(entry.failing, data.labels_of(entry.failing)),
                ]
            )
    lines += table(["model", "question", "right on", "why it failed on the other"], detail)
    return lines


def accuracy_section(inputs: ReportInputs) -> list[str]:
    data = inputs.data
    ranked = accuracy_by_warehouse(data)
    lines = [
        "## 4. Accuracy",
        "",
        "![Accuracy by model and warehouse](accuracy.png)",
        "",
        f"95% bootstrap intervals over questions ({RESAMPLES} resamples, seed {SEED}). "
        f"Differences whose interval contains zero are marked `{NOT_SIGNIFICANT}`.",
        "",
        "### Per model and warehouse",
        "",
    ]
    rows = []
    for entry in ranked:
        rows.append(
            [
                entry.model_id,
                with_interval(entry.by_warehouse[WAREHOUSES[0]]),
                with_interval(entry.by_warehouse[WAREHOUSES[1]]),
                gap_text(entry.gap),
            ]
        )
    lines += table(["model", *WAREHOUSES, "snowflake minus databricks (paired)"], rows)
    lines += ["### Each model against the next one down", ""]
    neighbour_rows = [
        [gap.warehouse, f"{gap.better} vs {gap.worse}", gap_text(gap.gap)]
        for gap in neighbour_gaps(data, ranked)
    ]
    lines += table(["warehouse", "models", "difference (paired)"], neighbour_rows)

    lines += [
        "### Portable vs dialect-sensitive questions",
        "",
        "Both warehouses pooled; the gap resamples each group's questions separately.",
        "",
    ]
    category_rows = [
        [gap.model_id, with_interval(gap.first), with_interval(gap.second), gap_text(gap.gap)]
        for gap in group_gaps(
            data,
            lambda question: question.category == Category.PORTABLE,
            lambda question: question.category == Category.DIALECT_SENSITIVE,
        )
    ]
    lines += table(
        ["model", "portable", "dialect-sensitive", "portable minus sensitive"], category_rows
    )

    lines += ["### Syntax vs semantics divergence", ""]
    divergence_rows = [
        [gap.model_id, with_interval(gap.first), with_interval(gap.second), gap_text(gap.gap)]
        for gap in group_gaps(
            data,
            lambda question: question.divergence == Divergence.SYNTAX,
            lambda question: question.divergence == Divergence.SEMANTICS,
        )
    ]
    lines += table(["model", "syntax", "semantics", "syntax minus semantics"], divergence_rows)

    lines += ["### By feature", "", "![Accuracy by feature](features.png)", ""]
    features = [feature.value for feature in Feature]
    by_feature = accuracy_by_group(data, features, lambda q: [f.value for f in q.features])
    lines += group_table(by_feature, data.models, features)

    lines += ["### By difficulty", ""]
    difficulties = [difficulty.value for difficulty in Difficulty]
    by_difficulty = accuracy_by_group(data, difficulties, lambda q: [q.difficulty.value])
    lines += group_table(by_difficulty, data.models, difficulties)
    return lines


def group_table(
    by_group: dict[str, dict[str, tuple[float, int]]], models: list[str], groups: list[str]
) -> list[str]:
    present = [group for group in groups if group in by_group[models[0]]]
    rows = []
    for group in present:
        count = by_group[models[0]][group][1]
        rows.append([group, str(count)] + [percent(by_group[m][group][0]) for m in models])
    return table(["group", "questions", *models], rows)


def lucky_section(inputs: ReportInputs) -> list[str]:
    rows = []
    for rate in lucky_rates(inputs.data):
        rows.append(
            [
                rate.model_id,
                f"{rate.lucky} of {rate.tasks}",
                percent(rate.main_only_accuracy),
                percent(rate.accuracy),
                f"{rate.overstatement * 100:+.1f} pp",
            ]
        )
    return [
        "## 5. What one dataset would have said",
        "",
        "A lucky match is correct on main and wrong on edge. Scoring on main alone would "
        "have counted these as correct.",
        "",
        *table(["model", "lucky matches", "main only", "main and edge", "overstated by"], rows),
    ]


def guard_section(inputs: ReportInputs) -> list[str]:
    lines = ["## 6. Read-only guard false positives", ""]
    checks = inputs.guard_checks
    if checks is None:
        return lines + ["Not checked: run `bench analysis guard-check`.", ""]
    accepted = [check for check in checks if check.accepted]
    lines += [
        f"Predictions the guard couldn't parse: {len(checks)}. They were scored as syntax "
        "errors without reaching a warehouse. Of these, EXPLAIN on the target warehouse "
        f"accepted: {len(accepted)}.",
        "",
    ]
    if accepted:
        lines += table(
            ["model", "warehouse", "question"],
            [[c.model_id, c.warehouse, c.question_id] for c in accepted],
        )
    return lines


def hand_label_section(inputs: ReportInputs) -> list[str]:
    lines = ["## 7. Labelled root causes", ""]
    labels = inputs.hand_labels
    if not labels:
        return lines + ["No labels yet: fill in `results/labels.csv`.", ""]
    counts: dict[str, Counter[str]] = {warehouse: Counter() for warehouse in WAREHOUSES}
    for label in labels:
        counts[label.key[1]][label.root_cause] += 1
    rows = [
        [cause.value] + [str(counts[w][cause]) for w in WAREHOUSES]
        for cause in RootCause
        if any(counts[w][cause] for w in WAREHOUSES)
    ]
    lines += [
        f"Failures labelled: {len(labels)}, {inputs.labeller}. A label made on an earlier "
        "run is kept only where the same task failed with the same SQL.",
        "",
    ]
    lines += table(["root cause", *WAREHOUSES], rows)
    lines += ["### Agreement with automatic labels", ""]
    agreements = agreement(inputs.data.labels, labels)
    agreement_rows = [
        [a.auto_label, a.root_cause.value, str(a.labelled), str(a.agreeing)] for a in agreements
    ]
    lines += table(
        ["automatic label", "matching root cause", "hand-labelled", "agree"], agreement_rows
    )
    return lines


def method_section() -> list[str]:
    return [
        "## Method",
        "",
        f"- Intervals: percentile bootstrap, {int(LEVEL * 100)}%, {RESAMPLES} resamples of "
        f"questions with replacement, seed {SEED}.",
        "- Paired differences (same questions) resample per-question differences; group "
        "gaps resample each group on its own.",
        "- Pooled accuracy counts a question as 0.5 when a model is right on one warehouse.",
        "",
    ]


def write_report(inputs: ReportInputs, output_dir: Path) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    data = inputs.data
    charts.failure_chart(failure_outcomes(data), output_dir / "failures.png")
    ranked = accuracy_by_warehouse(data)
    charts.accuracy_chart(ranked, output_dir / "accuracy.png")
    features = [feature.value for feature in Feature]
    by_feature = accuracy_by_group(data, features, lambda q: [f.value for f in q.features])
    ranked_models = [entry.model_id for entry in ranked]
    charts.feature_chart(by_feature, ranked_models, output_dir / "features.png")

    lines: list[str] = []
    lines += header_section(inputs)
    lines += failure_section(inputs)
    lines += example_section(inputs)
    lines += split_section(inputs)
    lines += accuracy_section(inputs)
    lines += lucky_section(inputs)
    lines += guard_section(inputs)
    lines += hand_label_section(inputs)
    lines += method_section()
    path = output_dir / "README.md"
    path.write_text("\n".join(lines))
    return path
